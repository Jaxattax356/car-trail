  const ADV = 6; // horizontal advance
  const LINE = 10; // line height
  const ROWS = 9;
  const CHARS = Object.keys(G);
  const index = new Map();
  CHARS.forEach((ch, i) => index.set(ch, i));

  function glyphBits(ch) {
    let g = G[ch];
    if (!g) g = G['?'];
    return g;
  }

  // ---- Canvas atlas (white glyphs), tinted per colour on demand ----
  let atlas = null;
  const tinted = new Map();
  function buildAtlas() {
    const cv = document.createElement('canvas');
    cv.width = CHARS.length * ADV;
    cv.height = ROWS;
    const cx = cv.getContext('2d');
    cx.fillStyle = '#fff';
    CHARS.forEach((ch, i) => {
      const g = G[ch];
      for (let y = 0; y < g.length; y++) {
        for (let x = 0; x < 5; x++) if (g[y][x] === '#') cx.fillRect(i * ADV + x, y, 1, 1);
      }
    });
    atlas = cv;
  }
  function atlasFor(color) {
    if (!atlas) buildAtlas();
    let t = tinted.get(color);
    if (t) return t;
    t = document.createElement('canvas');
    t.width = atlas.width;
    t.height = atlas.height;
    const cx = t.getContext('2d');
    cx.drawImage(atlas, 0, 0);
    cx.globalCompositeOperation = 'source-in';
    cx.fillStyle = color;
    cx.fillRect(0, 0, t.width, t.height);
    tinted.set(color, t);
    return t;
  }

  const font = {
    ADV, LINE, ROWS,
    width(str, scale) {
      const s = scale || 1;
      const n = String(str).length;
      return n ? (n * ADV - 1) * s : 0;
    },
    has(ch) { return index.has(ch); },
    // Draw text to a 2D context. opts: {scale, align:'left'|'center'|'right', shadow:colour}
    draw(ctx, str, x, y, color, opts) {
      str = String(str);
      const o = opts || {};
      const s = o.scale || 1;
      let px = Math.round(x);
      if (o.align === 'center') px = Math.round(x - font.width(str, s) / 2);
      else if (o.align === 'right') px = Math.round(x - font.width(str, s));
      const py = Math.round(y);
      if (o.shadow) font.draw(ctx, str, px + s, py + s, o.shadow, { scale: s });
      const at = atlasFor(color || '#fff');
      for (let i = 0; i < str.length; i++) {
        const ch = str[i];
        if (ch === ' ') continue;
        let gi = index.get(ch);
        if (gi === undefined) gi = index.get('?');
        ctx.drawImage(at, gi * ADV, 0, ADV, ROWS, px + i * ADV * s, py, ADV * s, ROWS * s);
      }
    },
    drawToBitmap(bmp, str, x, y, color, scale) {
      str = String(str);
      const s = scale || 1;
      const c = CT.gfx.col(color);
      for (let i = 0; i < str.length; i++) {
        const g = glyphBits(str[i]);
        for (let gy = 0; gy < g.length; gy++) {
          for (let gx = 0; gx < 5; gx++) {
            if (g[gy][gx] !== '#') continue;
            for (let sy = 0; sy < s; sy++) for (let sx = 0; sx < s; sx++) {
              bmp.pset(x + (i * ADV + gx) * s + sx, y + gy * s + sy, c);
            }
          }
        }
      }
    },
    // Characters accepted in typed names.
    isTypeable(ch) {
      return /^[A-Za-z0-9 .'\-!?&,]$/.test(ch);
    },
  };

  CT.font = font;
